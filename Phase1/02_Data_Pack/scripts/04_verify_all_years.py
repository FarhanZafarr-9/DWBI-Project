"""Verify the 2025 + 2026 raw download and write a markdown summary.

Usage: python scripts/04_verify_all_years.py
Requires: pandas (see requirements.txt)
"""
import pathlib, zipfile, glob, pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw_data"
OUT = ROOT / "DOWNLOAD_VERIFICATION.md"
lines = []

def say(s=""):
    lines.append(s)
    print(s, flush=True)

def zip_csv(path, **kwargs):
    with zipfile.ZipFile(path) as z:
        name = next(n for n in z.namelist() if n.lower().endswith(".csv"))
        return pd.read_csv(z.open(name), low_memory=False, **kwargs)

def mb(n):
    return f"{n / 1e6:.1f} MB"

say("# Raw Data Verification — 2025 + 2026")
say()
say("Generated by `scripts/04_verify_all_years.py`. Raw files are local and gitignored.")
say()

# ---- On-Time -------------------------------------------------------------
say("## BTS On-Time Performance")
say()
say("| Year | Months present | Rows | Airlines | Avg arr delay | Cancelled | Diverted |")
say("|---|---:|---:|---:|---:|---:|---:|")
need = ["FlightDate", "Reporting_Airline", "ArrDelay", "Cancelled", "Diverted"]
for year in (2025, 2026):
    paths = sorted(glob.glob(str(RAW / "bts_ontime" / f"ontime_{year}_*.zip")))
    if not paths:
        say(f"| {year} | 0 | — | — | — | — | — |")
        continue
    months = sorted(int(p.split("_")[-1].split(".")[0]) for p in paths)
    frames = [zip_csv(p, usecols=lambda c: c in need) for p in paths]
    df = pd.concat(frames, ignore_index=True)
    say(f"| {year} | {len(months)} ({months[0]}–{months[-1]}) | {len(df):,} | "
        f"{df.Reporting_Airline.nunique()} | {df.ArrDelay.mean():.1f} min | "
        f"{(df.Cancelled == 1).mean():.2%} | {(df.Diverted == 1).mean():.2%} |")
say()

# ---- DB1B ----------------------------------------------------------------
say("## BTS DB1B Market")
say()
qfiles = sorted(glob.glob(str(RAW / "bts_db1b" / "*.zip")))
if qfiles:
    say("| File | Size | Rows sampled | Non-stop share |")
    say("|---|---:|---:|---:|")
    for p in qfiles:
        d = zip_csv(p, nrows=200000)
        nonstop = (d["MktCoupons"] == 1).mean() if "MktCoupons" in d else float("nan")
        say(f"| {pathlib.Path(p).name} | {mb(pathlib.Path(p).stat().st_size)} | {len(d):,} | {nonstop:.1%} |")
else:
    say("No DB1B files downloaded.")
say()

# ---- FAA -----------------------------------------------------------------
say("## FAA Aircraft Registry")
say()
for name in ("MASTER.txt", "ACFTREF.txt", "DEREG.txt"):
    p = RAW / "faa" / name
    if p.exists():
        with p.open("rb") as f:
            n = sum(1 for _ in f)
        say(f"- `{name}` — {mb(p.stat().st_size)}, {n:,} lines")
    else:
        say(f"- `{name}` — MISSING")
say()

# ---- NOAA ----------------------------------------------------------------
say("## NOAA Global Hourly (2025)")
say()
wfiles = sorted(glob.glob(str(RAW / "noaa" / "K*_2025.csv")))
if wfiles:
    sizes = sum(pathlib.Path(p).stat().st_size for p in wfiles)
    say(f"- {len(wfiles)} station files, {mb(sizes)} total")
    first = pd.read_csv(wfiles[0], usecols=["DATE"], low_memory=False)
    say(f"- Sample `{pathlib.Path(wfiles[0]).name}`: {len(first):,} observations from {first.DATE.min()} to {first.DATE.max()}")
else:
    say("- No NOAA station files downloaded.")
say("- 2026 is not published in the NOAA Global Hourly bucket (checked 2026-11-17).")
say()

# ---- T-100 ---------------------------------------------------------------
say("## BTS T-100 Domestic Segment")
say()
tfiles = glob.glob(str(RAW / "bts_t100" / "*"))
say(f"- {len(tfiles)} file(s) present. This source has no bulk URL and must be downloaded manually from TranStats.")
say()

OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"\nReport written to {OUT}")
