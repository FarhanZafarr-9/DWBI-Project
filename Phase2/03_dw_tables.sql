-- Section 1: Dimension tables
CREATE TABLE IF NOT EXISTS project_dw.dim_date (
    date_key INT NOT NULL,
    full_date DATE NOT NULL,
    day_of_week VARCHAR(9) NOT NULL,
    week_of_year SMALLINT NOT NULL,
    month SMALLINT NOT NULL,
    month_name VARCHAR(9) NOT NULL,
    quarter SMALLINT NOT NULL,
    year SMALLINT NOT NULL,
    season VARCHAR(6) NOT NULL,
    is_weekend BOOLEAN NOT NULL,
    is_holiday BOOLEAN NOT NULL,
    holiday_name VARCHAR(40),
    CONSTRAINT pk_dim_date PRIMARY KEY (date_key),
    CONSTRAINT uq_dim_date_full_date UNIQUE (full_date)
);

CREATE TABLE IF NOT EXISTS project_dw.dim_time (
    time_key SMALLINT NOT NULL,
    hour_of_day SMALLINT NOT NULL,
    time_band VARCHAR(10) NOT NULL,
    is_peak BOOLEAN NOT NULL,
    CONSTRAINT pk_dim_time PRIMARY KEY (time_key),
    CONSTRAINT uq_dim_time_hour_of_day UNIQUE (hour_of_day)
);

CREATE TABLE IF NOT EXISTS project_dw.dim_airline (
    airline_key INT GENERATED BY DEFAULT AS IDENTITY,
    carrier_code VARCHAR(3) NOT NULL,
    airline_name VARCHAR(80),
    CONSTRAINT pk_dim_airline PRIMARY KEY (airline_key),
    CONSTRAINT uq_dim_airline_carrier_code UNIQUE (carrier_code)
);

CREATE TABLE IF NOT EXISTS project_dw.dim_airport (
    airport_key INT GENERATED BY DEFAULT AS IDENTITY,
    iata_code CHAR(3) NOT NULL,
    icao_code VARCHAR(4),
    airport_name VARCHAR(120) NOT NULL,
    city VARCHAR(80),
    state CHAR(2) NOT NULL,
    region VARCHAR(10) NOT NULL,
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    elevation_ft INT,
    airport_type VARCHAR(20),
    time_zone VARCHAR(40) NOT NULL,
    CONSTRAINT pk_dim_airport PRIMARY KEY (airport_key),
    CONSTRAINT uq_dim_airport_iata_code UNIQUE (iata_code)
);

CREATE TABLE IF NOT EXISTS project_dw.dim_route (
    route_key INT GENERATED BY DEFAULT AS IDENTITY,
    origin_code CHAR(3) NOT NULL,
    dest_code CHAR(3) NOT NULL,
    route_name VARCHAR(7) NOT NULL,
    distance_miles INT,
    distance_band VARCHAR(10),
    CONSTRAINT pk_dim_route PRIMARY KEY (route_key),
    CONSTRAINT uq_dim_route_route_name UNIQUE (route_name),
    CONSTRAINT uq_dim_route_origin_dest UNIQUE (origin_code, dest_code)
);

CREATE TABLE IF NOT EXISTS project_dw.dim_aircraft (
    aircraft_key INT GENERATED BY DEFAULT AS IDENTITY,
    tail_number VARCHAR(10) NOT NULL,
    manufacturer VARCHAR(60),
    model VARCHAR(60),
    engine_type VARCHAR(30),
    year_built SMALLINT,
    age_band VARCHAR(12),
    row_effective_date DATE,
    row_expiry_date DATE,
    is_current BOOLEAN,
    CONSTRAINT pk_dim_aircraft PRIMARY KEY (aircraft_key)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_dim_aircraft_current_tail
    ON project_dw.dim_aircraft (tail_number) WHERE is_current;

CREATE TABLE IF NOT EXISTS project_dw.dim_flight_status (
    status_key SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    status_code VARCHAR(12) NOT NULL,
    flight_status VARCHAR(10) NOT NULL,
    cancellation_reason VARCHAR(15),
    delay_category VARCHAR(20),
    CONSTRAINT pk_dim_flight_status PRIMARY KEY (status_key),
    CONSTRAINT uq_dim_flight_status_code UNIQUE (status_code)
);

CREATE TABLE IF NOT EXISTS project_dw.dim_weather_condition (
    weather_condition_key SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    condition_code VARCHAR(10) NOT NULL,
    condition VARCHAR(20) NOT NULL,
    visibility_band VARCHAR(15),
    CONSTRAINT pk_dim_weather_condition PRIMARY KEY (weather_condition_key),
    CONSTRAINT uq_dim_weather_condition_code UNIQUE (condition_code)
);

-- Section 2: Fact tables
CREATE SEQUENCE IF NOT EXISTS project_dw.seq_flight_key AS BIGINT;

CREATE TABLE IF NOT EXISTS project_dw.fact_flight (
    flight_key BIGINT NOT NULL DEFAULT nextval('project_dw.seq_flight_key'),
    date_key INT NOT NULL,
    sched_dep_time_key SMALLINT NOT NULL,
    airline_key INT NOT NULL,
    origin_airport_key INT NOT NULL,
    dest_airport_key INT NOT NULL,
    route_key INT NOT NULL,
    aircraft_key INT NOT NULL,
    status_key SMALLINT NOT NULL,
    flight_number VARCHAR(6),
    dep_delay_min SMALLINT,
    arr_delay_min SMALLINT,
    carrier_delay_min SMALLINT,
    weather_delay_min SMALLINT,
    nas_delay_min SMALLINT,
    security_delay_min SMALLINT,
    late_aircraft_delay_min SMALLINT,
    taxi_out_min SMALLINT,
    taxi_in_min SMALLINT,
    air_time_min SMALLINT,
    distance_miles INT,
    is_cancelled BOOLEAN NOT NULL,
    is_diverted BOOLEAN NOT NULL,
    flight_count SMALLINT NOT NULL DEFAULT 1,
    etl_batch_id INT NOT NULL,
    CONSTRAINT pk_fact_flight PRIMARY KEY (flight_key, date_key),
    CONSTRAINT fk_fact_flight_date FOREIGN KEY (date_key) REFERENCES project_dw.dim_date (date_key),
    CONSTRAINT fk_fact_flight_time FOREIGN KEY (sched_dep_time_key) REFERENCES project_dw.dim_time (time_key),
    CONSTRAINT fk_fact_flight_airline FOREIGN KEY (airline_key) REFERENCES project_dw.dim_airline (airline_key),
    CONSTRAINT fk_fact_flight_origin FOREIGN KEY (origin_airport_key) REFERENCES project_dw.dim_airport (airport_key),
    CONSTRAINT fk_fact_flight_dest FOREIGN KEY (dest_airport_key) REFERENCES project_dw.dim_airport (airport_key),
    CONSTRAINT fk_fact_flight_route FOREIGN KEY (route_key) REFERENCES project_dw.dim_route (route_key),
    CONSTRAINT fk_fact_flight_aircraft FOREIGN KEY (aircraft_key) REFERENCES project_dw.dim_aircraft (aircraft_key),
    CONSTRAINT fk_fact_flight_status FOREIGN KEY (status_key) REFERENCES project_dw.dim_flight_status (status_key)
) PARTITION BY RANGE (date_key);

DO $$
DECLARE
    y INT;
    m INT;
    from_key INT;
    to_key INT;
BEGIN
    FOR y IN 2025..2026 LOOP
        FOR m IN 1..12 LOOP
            from_key := y * 10000 + m * 100 + 1;
            to_key := CASE WHEN m = 12 THEN (y + 1) * 10000 + 101 ELSE y * 10000 + (m + 1) * 100 + 1 END;
            EXECUTE format(
                'CREATE TABLE IF NOT EXISTS project_dw.fact_flight_%s_%s PARTITION OF project_dw.fact_flight FOR VALUES FROM (%s) TO (%s)',
                y, lpad(m::TEXT, 2, '0'), from_key, to_key
            );
        END LOOP;
    END LOOP;
END $$;

CREATE TABLE IF NOT EXISTS project_dw.fact_flight_default PARTITION OF project_dw.fact_flight DEFAULT;

CREATE INDEX IF NOT EXISTS idx_fact_flight_date ON project_dw.fact_flight (date_key);
CREATE INDEX IF NOT EXISTS idx_fact_flight_time ON project_dw.fact_flight (sched_dep_time_key);
CREATE INDEX IF NOT EXISTS idx_fact_flight_airline ON project_dw.fact_flight (airline_key);
CREATE INDEX IF NOT EXISTS idx_fact_flight_origin ON project_dw.fact_flight (origin_airport_key);
CREATE INDEX IF NOT EXISTS idx_fact_flight_dest ON project_dw.fact_flight (dest_airport_key);
CREATE INDEX IF NOT EXISTS idx_fact_flight_route ON project_dw.fact_flight (route_key);
CREATE INDEX IF NOT EXISTS idx_fact_flight_aircraft ON project_dw.fact_flight (aircraft_key);
CREATE INDEX IF NOT EXISTS idx_fact_flight_status ON project_dw.fact_flight (status_key);

